'use client';

import { Bot, TrendingUp, AlertCircle, CheckCircle2, Sparkles, RefreshCw } from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import { Ticket } from '@/types';

type InsightsProps = {
  summary: {
    overall_status: string;
    summary_text: string;
  };
  tickets: Ticket[];
  processing: boolean;
  handleProcess: () => void;
};

export default function Insights({
  summary,
  tickets,
  processing,
  handleProcess,
}: InsightsProps) {
  const bugCount = tickets.filter((t) => t.issue_type === 'Bug').length;
  const storyCount = tickets.filter((t) => t.issue_type === 'Story').length;
  const epicCount = tickets.filter((t) => t.issue_type === 'Epic').length;

  return (
    <div className="space-y-6 animate-fade-in">
      {/* ── Main Executive Summary Card ── */}
      <div
        className="glass rounded-2xl p-6 sm:p-8 relative overflow-hidden"
        style={{
          background: 'rgba(255, 255, 255, 0.03)',
          border: '1px solid rgba(255, 255, 255, 0.08)',
          boxShadow: '0 4px 24px rgba(0,0,0,0.2)',
        }}
      >
        {/* Top glowing gradient border */}
        <div
          className="absolute top-0 left-0 right-0 h-1"
          style={{ background: 'linear-gradient(90deg, #6366f1, #a855f7, #ec4899)' }}
        />

        {/* Card Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-6 border-b border-white/10 mb-6">
          <div className="flex items-center gap-3">
            <div
              className="w-10 h-10 rounded-xl flex items-center justify-center shrink-0 shadow-lg shadow-indigo-500/20"
              style={{ background: 'linear-gradient(135deg, #6366f1, #a855f7)' }}
            >
              <Bot className="w-5 h-5 text-white" />
            </div>
            <div>
              <h2 className="text-xl font-bold text-white tracking-tight">Executive AI Risk Intelligence</h2>
              <p className="text-xs text-slate-400">Automated project health synthesis generated by LangGraph</p>
            </div>
          </div>

          <button
            onClick={handleProcess}
            disabled={processing}
            className="glass px-4 py-2.5 rounded-xl text-xs sm:text-sm font-semibold text-slate-200 hover:text-white border border-white/10 hover:border-white/20 transition-all flex items-center gap-2 cursor-pointer shadow-md self-start sm:self-auto disabled:opacity-50"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${processing ? 'animate-spin text-indigo-400' : ''}`} />
            <span>{processing ? 'Synthesizing...' : 'Refresh Insights'}</span>
          </button>
        </div>

        {/* ── Top Summary Stat Cards ── */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 mb-6 pb-6 border-b border-white/10">
          <div className="glass p-4 rounded-xl flex items-center gap-3.5">
            <div className="w-10 h-10 rounded-xl bg-blue-500/15 border border-blue-500/25 flex items-center justify-center text-blue-400 shrink-0">
              <TrendingUp className="w-5 h-5" />
            </div>
            <div>
              <p className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">Overall Project Health</p>
              <p className="font-bold text-base text-white">{summary.overall_status}</p>
            </div>
          </div>

          <div className="glass p-4 rounded-xl flex items-center gap-3.5">
            <div className="w-10 h-10 rounded-xl bg-rose-500/15 border border-rose-500/25 flex items-center justify-center text-rose-400 shrink-0">
              <AlertCircle className="w-5 h-5" />
            </div>
            <div>
              <p className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">Identified Defects</p>
              <p className="font-bold text-base text-white">{bugCount} Bugs</p>
            </div>
          </div>

          <div className="glass p-4 rounded-xl flex items-center gap-3.5">
            <div className="w-10 h-10 rounded-xl bg-emerald-500/15 border border-emerald-500/25 flex items-center justify-center text-emerald-400 shrink-0">
              <CheckCircle2 className="w-5 h-5" />
            </div>
            <div>
              <p className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">Feature Scope</p>
              <p className="font-bold text-base text-white">{storyCount} Stories • {epicCount} Epics</p>
            </div>
          </div>
        </div>

        {/* Markdown Content Area */}
        <div className="text-slate-300 leading-relaxed text-sm">
          {processing ? (
            <div className="space-y-3 py-4">
              <div className="h-4 bg-white/10 rounded-full w-full animate-pulse" />
              <div className="h-4 bg-white/10 rounded-full w-[92%] animate-pulse" />
              <div className="h-4 bg-white/10 rounded-full w-[96%] animate-pulse" />
              <div className="h-4 bg-white/10 rounded-full w-[80%] animate-pulse" />
              <div className="h-4 bg-white/10 rounded-full w-[65%] animate-pulse pt-2" />
              <div className="h-4 bg-white/10 rounded-full w-[88%] animate-pulse" />
            </div>
          ) : (
            <div className="prose prose-invert max-w-none text-slate-300">
              <ReactMarkdown
                components={{
                  h1: ({ node, ...props }) => (
                    <h1 className="text-xl font-bold text-white mt-6 mb-3 border-b border-white/10 pb-2" {...props} />
                  ),
                  h2: ({ node, ...props }) => (
                    <h2 className="text-lg font-bold text-white mt-5 mb-2.5 flex items-center gap-2" {...props} />
                  ),
                  h3: ({ node, ...props }) => (
                    <h3 className="text-base font-semibold text-indigo-300 mt-4 mb-2" {...props} />
                  ),
                  p: ({ node, ...props }) => <p className="mb-4 leading-relaxed text-slate-300" {...props} />,
                  ul: ({ node, ...props }) => (
                    <ul className="list-disc pl-5 mb-4 space-y-1.5 marker:text-indigo-400" {...props} />
                  ),
                  ol: ({ node, ...props }) => (
                    <ol className="list-decimal pl-5 mb-4 space-y-1.5 marker:text-indigo-400" {...props} />
                  ),
                  li: ({ node, ...props }) => <li className="text-slate-300" {...props} />,
                  strong: ({ node, ...props }) => <strong className="font-bold text-white" {...props} />,
                  a: ({ node, ...props }) => (
                    <a className="text-indigo-400 hover:text-indigo-300 underline font-medium" {...props} />
                  ),
                  blockquote: ({ node, ...props }) => (
                    <blockquote
                      className="border-l-4 border-indigo-500 pl-4 py-1.5 my-4 bg-indigo-500/10 rounded-r-xl italic text-slate-200"
                      {...props}
                    />
                  ),
                  code: ({ node, className, children, ...props }: any) => {
                    const match = /language-(\w+)/.exec(className || '');
                    return !match ? (
                      <code className="bg-black/40 text-indigo-300 px-1.5 py-0.5 rounded text-xs font-mono border border-white/10" {...props}>
                        {children}
                      </code>
                    ) : (
                      <code className="block bg-black/40 text-slate-200 p-4 rounded-xl text-xs font-mono border border-white/10 overflow-x-auto mb-4 custom-scrollbar" {...props}>
                        {children}
                      </code>
                    );
                  },
                }}
              >
                {(summary.summary_text || 'No insights available yet. Please run AI analysis on your tickets.').replace(/\\n/g, '\n')}
              </ReactMarkdown>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
